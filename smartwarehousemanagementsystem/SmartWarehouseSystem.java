package com.tit.javagenerics.smartwarehousemanagementsystem;
public class SmartWarehouseSystem {
    public static void main(String[] args) {
        // Create storage for different item types
        Storage<Electronics> electronicsStorage = new Storage<>();
        electronicsStorage.addItem(new Electronics("Smartphone", "OnePlus"));

        Storage<Groceries> groceriesStorage = new Storage<>();
        groceriesStorage.addItem(new Groceries("Milk", "2025-03-01"));

        Storage<Furniture> furnitureStorage = new Storage<>();
        furnitureStorage.addItem(new Furniture("Chair", "Wood"));

        // Display stored items using wildcard method
        System.out.println("Warehouse Inventory:");
        Storage.displayItems(electronicsStorage.getItems());
        Storage.displayItems(groceriesStorage.getItems());
        Storage.displayItems(furnitureStorage.getItems());
    }
}

















































































































































































